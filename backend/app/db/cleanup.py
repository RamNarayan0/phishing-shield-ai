def is_synthetic_test_artifact(doc: Dict[str, Any]) -> bool:
    """
    Identifies transient test artifacts generated by automated test runners.
    Criteria:
    1. Empty raw_text (generated by edge-case test payloads).
    2. source_platform is 'web_test' or 'load_test'.
    3. raw_text begins with automated test prefixes ('Security alert test for user account',
       'Duplicate test payload', 'Concurrent blast test').
    """
    text = (doc.get("raw_text") or "").strip()
    src = (doc.get("source_platform") or "").strip().lower()

    if not text:
        return True
    if src in ("web_test", "load_test"):
        return True
    if text.startswith("Security alert test for user account"):
        return True
    if text.startswith("Duplicate test payload"):
        return True
    if text.startswith("Concurrent blast test"):
        return True
    return False

def create_backup(collection=None, db=None) -> Dict[str, Any]:
    """
    Creates an exact point-in-time snapshot of the target collection
    before any cleanup or destructive operation is executed.
    """
    target_coll = collection if collection is not None else _collection
    target_db = db if db is not None else (target_coll.database if target_coll is not None else _db)

    if target_coll is None or target_db is None:
        return {"status": "skipped", "message": "No active MongoDB collection to backup."}

    docs = list(target_coll.find({}))
    now_str = datetime.now(timezone.utc).strftime("%Y%m%d_%H%M%S_%f")
    backup_name = f"{target_coll.name}_backup_{now_str}"

    if docs:
        # Clone documents removing original _id so fresh copies are inserted cleanly
        clone_docs = []
        for d in docs:
            copy = dict(d)
            copy.pop("_id", None)
            clone_docs.append(copy)
        target_db[backup_name].insert_many(clone_docs)

    logger.info(f"Created collection backup '{backup_name}' with {len(docs)} documents.")

    return {
        "status": "success",
        "backup_collection": backup_name,
        "backed_up_count": len(docs),
        "timestamp": datetime.now(timezone.utc).isoformat()
    }

def clean_duplicates(
    collection=None,
    dry_run: bool = True,
    cross_source: bool = False,
    purge_test_artifacts: bool = True
) -> Dict[str, Any]:
    """
    Scans a MongoDB collection for duplicate analysis submissions and test clutter.

    Documented Deduplication Rule:
    - Normalization: Message text is trimmed, lowercased, and internal whitespace is collapsed.
    - Sender ID: Normalized to trimmed lowercase.
    - Source Platform: Evaluated per configuration:
      * When cross_source=False (default): Messages from distinct ingress channels (e.g. WhatsApp vs SMS)
        remain distinct source-specific records.
      * When cross_source=True: Messages sharing identical content and sender are consolidated across
        channels into a single canonical record with an `observed_sources` array.
    - Canonical Record Preservation: Earliest record (by created_at / timestamp) is preserved.
    - Explanation Preservation: Rich Explainable Phishing Risk Breakdown is retained from the best analysis.
    - Audit Trail: duplicate_count is aggregated, and last_seen_at reflects the most recent occurrence.
    - Safety: Backs up data before modification. dry_run=True by default.
    """
    target_coll = collection if collection is not None else _collection
    now_iso = datetime.now(timezone.utc).isoformat()

    if target_coll is None:
        return {
            "status": "skipped",
            "message": "No active MongoDB collection provided or connected.",
            "dry_run": dry_run,
            "total_records_before": 0,
            "duplicate_groups_found": 0,
            "redundant_records_identified": 0,
            "test_artifacts_identified": 0,
            "records_purged": 0,
            "total_records_after": 0,
            "timestamp": now_iso
        }

    docs = list(target_coll.find({}))
    total_before = len(docs)

    test_artifact_ids = []
    analyzable_docs = []

    for d in docs:
        if purge_test_artifacts and is_synthetic_test_artifact(d):
            test_artifact_ids.append(d["_id"])
        else:
            analyzable_docs.append(d)

    # Group documents by canonical identity key
    groups: Dict[str, List[Dict[str, Any]]] = {}
    for doc in analyzable_docs:
        norm_text = " ".join((doc.get("raw_text") or "").strip().lower().split())
        norm_sender = (doc.get("sender_id") or "").strip().lower()

        if cross_source:
            group_key = f"text:{norm_text}|sender:{norm_sender}"
            group_id = hashlib.sha256(group_key.encode("utf-8")).hexdigest()
        else:
            norm_source = (doc.get("source_platform") or "").strip().lower()
            group_key = f"text:{norm_text}|sender:{norm_sender}|src:{norm_source}"
            group_id = doc.get("fingerprint") or hashlib.sha256(group_key.encode("utf-8")).hexdigest()

        groups.setdefault(group_id, []).append(doc)


    duplicate_groups = 0
    redundant_ids = []
    canonical_updates = []

    for fp, group in groups.items():
        if len(group) > 1:
            duplicate_groups += 1
            # Sort chronologically ascending to pick the earliest canonical document
            sorted_group = sorted(
                group,
                key=lambda d: d.get("created_at") or d.get("timestamp") or ""
            )
            canonical = sorted_group[0]
            redundant = sorted_group[1:]

            redundant_ids.extend([d["_id"] for d in redundant])

            # Aggregate audit metrics
            total_dup_count = sum(d.get("duplicate_count", 1) for d in group)
            latest_seen = max(
                (d.get("last_seen_at") or d.get("created_at") or now_iso)
                for d in group
            )

            # Consolidate observed sources
            observed_sources = set()
            for d in group:
                if d.get("source_platform"):
                    observed_sources.add(d["source_platform"])
                for s in d.get("observed_sources", []):
                    observed_sources.add(s)

            # Preserve best explanation breakdown if canonical is missing it
            best_result = canonical.get("result", {})
            if "explanation" not in best_result:
                for d in group:
                    if "explanation" in d.get("result", {}):
                        best_result = d["result"]
                        break

            canonical_updates.append({
                "_id": canonical["_id"],
                "fingerprint": fp,
                "duplicate_count": total_dup_count,
                "last_seen_at": latest_seen,
                "observed_sources": list(observed_sources),
                "result": best_result
            })

    total_purged = 0
    backup_info = None

    if not dry_run:
        # 1. Automatic pre-cleanup snapshot backup
        backup_info = create_backup(target_coll)

        # 2. Delete test artifacts
        if test_artifact_ids:
            del_test_res = target_coll.delete_many({"_id": {"$in": test_artifact_ids}})
            total_purged += del_test_res.deleted_count

        # 3. Delete redundant duplicate records
        if redundant_ids:
            del_dup_res = target_coll.delete_many({"_id": {"$in": redundant_ids}})
            total_purged += del_dup_res.deleted_count

        # 4. Update canonical records with merged metrics
        for update in canonical_updates:
            target_coll.update_one(
                {"_id": update["_id"]},
                {
                    "$set": {
                        "fingerprint": update["fingerprint"],
                        "duplicate_count": update["duplicate_count"],
                        "last_seen_at": update["last_seen_at"],
                        "observed_sources": update["observed_sources"],
                        "result": update["result"]
                    }
                }
            )

    total_after = total_before - (len(test_artifact_ids) + len(redundant_ids)) if not dry_run else total_before

    report = {
        "status": "success",
        "dry_run": dry_run,
        "backup": backup_info,
        "total_records": total_before,
        "total_records_before": total_before,
        "unique_fingerprints": len(groups),
        "duplicate_groups": duplicate_groups,
        "duplicate_groups_found": duplicate_groups,
        "redundant_records_identified": len(redundant_ids),
        "redundant_records_removed": total_purged,
        "test_artifacts_identified": len(test_artifact_ids),
        "records_purged": total_purged,
        "total_records_after": total_after,
        "canonical_records_preserved": len(groups),
        "timestamp": now_iso
    }

    logger.info(f"Duplicate cleanup audit complete: {report}")
    return report

